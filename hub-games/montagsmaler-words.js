export function normalizeWord(str) {
  return String(str || "")
    .trim()
    .toLowerCase()
    .replace(/ä/g, "ae")
    .replace(/ö/g, "oe")
    .replace(/ü/g, "ue")
    .replace(/ß/g, "ss")
    .replace(/[\s\-_'".!?,]/g, "");
}

export function levenshtein(a, b) {
  const an = a.length, bn = b.length;
  if (!an) return bn;
  if (!bn) return an;
  const matrix = [];
  for (let i = 0; i <= bn; i++) matrix[i] = [i];
  for (let j = 0; j <= an; j++) matrix[0][j] = j;
  for (let i = 1; i <= bn; i++) {
    for (let j = 1; j <= an; j++) {
      if (b.charAt(i - 1) === a.charAt(j - 1)) {
        matrix[i][j] = matrix[i - 1][j - 1];
      } else {
        matrix[i][j] = Math.min(
          matrix[i - 1][j - 1] + 1,
          matrix[i][j - 1] + 1,
          matrix[i - 1][j] + 1
        );
      }
    }
  }
  return matrix[bn][an];
}

export function isNearGuess(guess, target) {
  const normG = normalizeWord(guess);
  const normT = normalizeWord(target);
  if (!normG || !normT || normG === normT) return false;
  const dist = levenshtein(normG, normT);
  if (normT.length <= 4) return dist === 1;
  if (normT.length <= 8) return dist <= 1;
  return dist <= 2;
}

export function getRandomWordOptions(lang = "de", categories = ["standard"], customWords = [], count = 3) {
  const langKey = lang === "en" ? "en" : "de";
  const pool = new Set();

  const langPack = WORDS[langKey] || WORDS.de;
  for (const cat of categories) {
    if (langPack[cat]) {
      for (const w of langPack[cat]) pool.add(w);
    }
  }

  if (Array.isArray(customWords)) {
    for (const w of customWords) {
      const trimmed = String(w || "").trim();
      if (trimmed.length >= 2) pool.add(trimmed);
    }
  }

  if (pool.size === 0) {
    for (const w of langPack.standard) pool.add(w);
  }

  const list = Array.from(pool);
  // Shuffle list
  for (let i = list.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [list[i], list[j]] = [list[j], list[i]];
  }

  return list.slice(0, Math.min(count, list.length));
}
